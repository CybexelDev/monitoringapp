    CHAT_PUSH_KEY_DIR.mkdir(exist_ok=True)
    (CHAT_PUSH_KEY_DIR / "private.pem").write_bytes(base64.b64decode(_pem_b64))
    (CHAT_PUSH_KEY_DIR / "public.txt").write_text(_pub.strip(), encoding="utf-8")

